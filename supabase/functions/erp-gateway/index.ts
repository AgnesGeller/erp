import {createWorkpack} from './workpack.ts';
import {makeWorkpackPdf} from './workpack-pdf.ts';
import {createMaintenance} from './maintenance.ts';
import {createFinance} from './finance.ts';
import {createMaterials} from './materials.ts';
import {createWorksheets} from './worksheets.ts';
import {createStaffAccess} from './staff.ts';
import {createEntries} from './entries.ts';
import {createWorkPlans} from './workplans.ts';
import {createClientAccess} from './clients.ts';
import {createGateway} from './handler.ts';
import {createCustomerDirectory} from './customers.ts';
import {createQuotes} from './quotes.ts';
import {createSurveys} from './surveys.ts';
import {makeQuotePdf} from './quote-pdf.ts';
const url=Deno.env.get('SUPABASE_URL')??'',key=Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')??'';
const customers=createCustomerDirectory({url,key,sourceKey:Deno.env.get('KASSZA_SERVICE_ROLE_KEY')??''});
const quotes=createQuotes({url,key,context:(organization_id,customer_id,token,actor,memberships)=>customers({action:'quote_context',organization_id,customer_id},token,actor,memberships),pdf:makeQuotePdf});
const surveys=createSurveys({url,key,context:(organization_id,customer_id,token,actor,memberships)=>customers({action:'work_sites',organization_id,customer_id},token,actor,memberships)});
const clients=createClientAccess({url,key,anonKey:Deno.env.get('SUPABASE_ANON_KEY')??'',pdf:makeQuotePdf});
const staff=createStaffAccess({url,key,anonKey:Deno.env.get('SUPABASE_ANON_KEY')??''});
const plans=createWorkPlans({url,key,materialNotifications:true,financeNotifications:true,maintenanceNotifications:true});
const materials=createMaterials({url,key});
const maintenance=createMaintenance({url,key,context:(org,customer,token,actor,memberships)=>customers({action:'work_sites',organization_id:org,customer_id:customer},token,actor,memberships),pdf:makeQuotePdf});
const finance=createFinance({url,key});
const entries=createEntries({url,key});
const sheets=createWorksheets({url,key});
const workpack=createWorkpack({plans,entries,sheets,materials,finance,pdf:makeWorkpackPdf});
Deno.serve(createGateway({workpack,maintenance,finance,materials,sheets,entries,staff:staff.handle,plans,clients:clients.handle,clientSession:async token=>{await clients.check(token);await staff.check(token);},clientLogout:async(token,actor)=>{await clients.close(token,actor);await staff.close(token,actor);},url,anonKey:Deno.env.get('SUPABASE_ANON_KEY')??'',serviceKey:key,emailFlowsEnabled:false,customers,quotes,surveys}));
